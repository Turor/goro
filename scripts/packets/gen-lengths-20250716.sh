#!/usr/bin/env bash
# Regenerates network/packet_lengths_20250716.go from a Hercules source tree.
#
#   scripts/packets/gen-lengths-20250716.sh /opt/hercules-test/src > network/packet_lengths_20250716.go
#
# Needs a C compiler. It compiles Hercules common/packets_len.h with
# PACKETVER=20250716 and prints every packetLen() entry. Turoran custom
# plugin packets are not in that header; they live in packet_profile.go.
set -euo pipefail
src="${1:?usage: gen-lengths-20250716.sh <hercules src dir>}"
tmp=$(mktemp -d)
trap "rm -rf \"$tmp\"" EXIT
cat >"$tmp/gen.c" <<C
#include <stdio.h>
#define PACKETVER 20250716
#define packetLen(id, len) printf("\t0x%04X: %d,\n", id, len);
int main(void) {
#include "common/packets_len.h"
	return 0;
}
C
cc -I"$src" -o "$tmp/gen" "$tmp/gen.c"
rev=$(git -C "$src" rev-parse --short=9 HEAD 2>/dev/null || echo unknown)
cat <<GO
// Code generated by scripts/packets/gen-lengths-20250716.sh; DO NOT EDIT.

package network

// packetLengths20250716Hercules is the Hercules length table for PACKETVER
// 20250716 (main client), from common/packets_len.h at Hercules $rev.
// Hercules statically asserts that every fixed packet struct matches it.
var packetLengths20250716Hercules = LengthTable{
GO
"$tmp/gen" | sort -u
echo "}"
